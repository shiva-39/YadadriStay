# Mapping from R.string.xxx to Str.xxx
# We need to convert R.string.foo_bar to Str.foo_bar
# But we also need to handle the imports

for file_path in files_to_fix:
    if not os.path.exists(file_path):
        print(f"File not found: {file_path}")
        continue

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    original_content = content

    # Add import for Str if not present
    if 'import com.yadadristay.presentation.components.Str' not in content:
        # Add after the package declaration
        content = content.replace(
            'package com.yadadristay.presentation',
            'package com.yadadristay.presentation\n\nimport com.yadadristay.presentation.components.Str'
        )

    # Replace R.string.xxx with Str.xxx
    # The pattern is R.string. followed by the name
    def replace_r_string(match):
        full = match.group(0)
        name = match.group(1)
        return f'Str.{name}'

    content = re.sub(r'R\.string\.(\w+)', replace_r_string, content)

    if content != original_content:
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Fixed: {file_path}")
    else:
        print(f"No changes needed: {file_path}")

print("Done!")