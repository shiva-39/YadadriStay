def fix_file(file_path):
    if not os.path.exists(file_path):
        print(f"File not found: {file_path}")
        return False

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    original_content = content

    # Check if Str import already exists
    has_str_import = 'import com.yadadristay.presentation.components.Str' in content

    # Replace all hex values with Str constants
    for hex_val, const_name in HEX_TO_CONST.items():
        # Pattern: str(context, 0x7F0Fxxxx) or str(LocalContext.current, 0x7F0Fxxxx)
        # Replace with str(context, Str.const_name)
        pattern = rf'str\(([^,]+),\s*{re.escape(hex_val)}\)'
        replacement = rf'str(\1, Str.{const_name})'
        content = re.sub(pattern, replacement, content)

    # Add Str import if needed and if any replacements were made
    if content != original_content and not has_str_import:
        # Add import after package declaration
        content = content.replace(
            'package com.yadadristay.presentation',
            'package com.yadadristay.presentation\n\nimport com.yadadristay.presentation.components.Str'
        )

    if content != original_content:
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Fixed: {file_path}")
        return True
    else:
        print(f"No changes needed: {file_path}")
        return False

def main():
    fixed_count = 0
    for file_path in FILES_TO_FIX:
        if fix_file(file_path):
            fixed_count += 1
    print(f"\nTotal files fixed: {fixed_count}")

if __name__ == '__main__':
    main()